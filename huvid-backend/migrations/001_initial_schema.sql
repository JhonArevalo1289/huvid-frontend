CREATE TABLE IF NOT EXISTS roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  descripcion VARCHAR(200),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS localidades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rol_id BIGINT NOT NULL REFERENCES roles(id),
  nombre VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  telefono VARCHAR(30),
  password_hash TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS casos_emergencia (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
  localidad_id BIGINT NOT NULL REFERENCES localidades(id),
  tipo VARCHAR(40) NOT NULL CHECK (tipo IN ('maltrato', 'perdido', 'lesionado', 'abandono')),
  direccion TEXT NOT NULL,
  descripcion TEXT NOT NULL,
  urgencia VARCHAR(20) NOT NULL CHECK (urgencia IN ('baja', 'media', 'alta', 'critica')),
  evidencia_url TEXT,
  estado VARCHAR(30) NOT NULL DEFAULT 'recibido'
    CHECK (estado IN ('recibido', 'en_revision', 'en_atencion', 'resuelto', 'cerrado')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE casos_emergencia
  ADD COLUMN IF NOT EXISTS evidencia_url TEXT;

CREATE TABLE IF NOT EXISTS mascotas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  especie VARCHAR(60) NOT NULL,
  raza VARCHAR(100),
  edad VARCHAR(60),
  descripcion TEXT,
  salud VARCHAR(100),
  ubicacion VARCHAR(120),
  localidad_id BIGINT REFERENCES localidades(id),
  imagen_url TEXT,
  estado VARCHAR(30) NOT NULL DEFAULT 'disponible'
    CHECK (estado IN ('disponible', 'solicitado', 'adoptado', 'no_disponible')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE mascotas
  ADD COLUMN IF NOT EXISTS edad VARCHAR(60),
  ADD COLUMN IF NOT EXISTS descripcion TEXT;

CREATE TABLE IF NOT EXISTS solicitudes_adopcion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mascota_id BIGINT NOT NULL REFERENCES mascotas(id),
  usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
  nombre_solicitante VARCHAR(120) NOT NULL,
  telefono VARCHAR(30) NOT NULL,
  motivo TEXT NOT NULL,
  direccion TEXT NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'recibida'
    CHECK (estado IN ('recibida', 'en_revision', 'aprobada', 'rechazada', 'cancelada')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS veterinarias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(160) NOT NULL,
  direccion TEXT NOT NULL,
  telefono VARCHAR(30) NOT NULL,
  horario_atencion VARCHAR(200) NOT NULL,
  servicios TEXT[] NOT NULL DEFAULT '{}',
  localidad_id BIGINT NOT NULL REFERENCES localidades(id),
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS noticias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  autor_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
  titulo VARCHAR(200) NOT NULL,
  resumen TEXT,
  contenido TEXT NOT NULL,
  imagen_url TEXT,
  publicada BOOLEAN NOT NULL DEFAULT FALSE,
  publicada_en TIMESTAMPTZ,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_usuarios_rol_id ON usuarios(rol_id);
CREATE INDEX IF NOT EXISTS idx_casos_localidad_estado ON casos_emergencia(localidad_id, estado);
CREATE INDEX IF NOT EXISTS idx_mascotas_estado ON mascotas(estado);
CREATE INDEX IF NOT EXISTS idx_solicitudes_mascota_estado ON solicitudes_adopcion(mascota_id, estado);
CREATE INDEX IF NOT EXISTS idx_veterinarias_localidad_activas ON veterinarias(localidad_id, activa);
CREATE INDEX IF NOT EXISTS idx_noticias_publicada_fecha ON noticias(publicada, publicada_en DESC);

